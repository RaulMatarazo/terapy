export default function GetEmocao(id){
    if (id == '1'){
        return 'Alegria'
    } else if (id == '2'){
        return 'Supresa'
    } else if (id == '3'){
        return 'Tristeza'
    } else if (id == '4'){
        return 'Neutro'
    } else if (id == '5'){
        return 'Repugância'
    } else if (id == '6'){
        return 'Raiva'
    } else if (id == '7'){
        return 'Medo'
    } 
}