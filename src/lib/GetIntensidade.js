export default function GetIntensidade(id){
    if (id == '1'){
        return 'Muito Fraco'
    } else if (id == '2'){
        return 'Fraco'
    } else if (id == '3'){
        return 'Baixo'
    } else if (id == '4'){
        return 'Normal'
    } else if (id == '5'){
        return 'Forte'
    } else if (id == '6'){
        return 'Muito Forte'
    } else if (id == '7'){
        return 'Extremo'
    } 
}